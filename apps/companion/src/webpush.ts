/**
 * Seals a phone alert for one Web Push subscription: RFC 8291 (aes128gcm content coding, ECDH P-256 + HKDF-SHA-256), with node:crypto only.
 * This runs on the user's computer. The relay and the push service get ciphertext they cannot open; the subscription's keys (p256dh, auth) reach
 * this computer only through the end-to-end encrypted channel, never the relay. Host side only: it is not part of the browser client.
 * Licence: Apache-2.0.
 */
import { createCipheriv, createECDH, hkdfSync, randomBytes } from 'node:crypto';
import { AlertPayload, type PushSub } from './protocol/index.ts';

/** Fixed inputs for the RFC 8291 Appendix A test vector; production never passes any of them. */
export interface EncryptFixed { asPrivate: Buffer; salt: Buffer }

const fromB64u = (s: string): Buffer => Buffer.from(s, 'base64url');

/** returns the complete request body (header + one record) */
export function encryptForSubscription(sub: Pick<PushSub, 'p256dh' | 'auth'>, plaintext: Buffer, fixed?: EncryptFixed): Buffer {
  const uaPublic = fromB64u(sub.p256dh);
  const authSecret = fromB64u(sub.auth);
  if (uaPublic.length !== 65 || uaPublic[0] !== 4) throw new Error('bad_p256dh');
  if (authSecret.length !== 16) throw new Error('bad_auth');
  if (plaintext.length > 3993) throw new Error('payload_too_large');
  const as = createECDH('prime256v1');
  if (fixed) as.setPrivateKey(fixed.asPrivate); else as.generateKeys();
  const asPublic = as.getPublicKey();
  const ecdhSecret = as.computeSecret(uaPublic);
  const salt = fixed ? fixed.salt : randomBytes(16);
  const keyInfo = Buffer.concat([Buffer.from('WebPush: info\0'), uaPublic, asPublic]);
  const ikm = Buffer.from(hkdfSync('sha256', ecdhSecret, authSecret, keyInfo, 32));
  const cek = Buffer.from(hkdfSync('sha256', ikm, salt, Buffer.from('Content-Encoding: aes128gcm\0'), 16));
  const nonce = Buffer.from(hkdfSync('sha256', ikm, salt, Buffer.from('Content-Encoding: nonce\0'), 12));
  const cipher = createCipheriv('aes-128-gcm', cek, nonce);
  const ct = Buffer.concat([cipher.update(Buffer.concat([plaintext, Buffer.from([2])])), cipher.final(), cipher.getAuthTag()]);
  const rs = Buffer.alloc(4); rs.writeUInt32BE(4096);
  return Buffer.concat([salt, rs, Buffer.from([asPublic.length]), asPublic, ct]);
}

/**
 * The one alert there is. `rid` is the random id of the request, so a tap can open it; it is not content (it is generated by this computer and means
 * nothing outside it). The words the person reads are fixed in the phone page's service worker, never taken from this payload.
 */
export function sealAlert(sub: PushSub, rid?: string): Buffer {
  const payload = AlertPayload.parse({ v: 1, k: 'waiting', ...(rid ? { r: rid } : {}) });
  return encryptForSubscription(sub, Buffer.from(JSON.stringify(payload)));
}
